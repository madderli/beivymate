const { chromium } = require(process.cwd() + '/src/frontend/node_modules/@playwright/test');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const check = (value, message) => { if (!value) throw Error(message); };
  await page.goto('http://127.0.0.1:5175/');
  await page.getByRole('heading', { name: '我的工作流', exact: true }).waitFor();
  check(await page.locator('.compact-flow-card').count() === 2, 'compact workflow cards');
  check(!await page.locator('#crumb').isVisible() && !await page.locator('#bell').isVisible(), 'remove redundant breadcrumb and task reminders');
  await page.screenshot({ path: '/tmp/workflow-library-demo.png', fullPage: true });
  await page.getByRole('button', { name: '＋ 新建工作流', exact: true }).click();
  await page.locator('[name=flowName]').fill('评审与摘要');
  await page.locator('[name=flowDescription]').fill('评审需求并整理结论。');
  await page.locator('[name=flowInput]').fill('提供需求规则以及本次评审的重点范围。');
  await page.locator('[name=flowConfirmation]').selectOption('自动继续');
  check(!(await page.locator('[name=skill0]').textContent()).includes('服务巡检'), 'other role hidden');
  check((await page.locator('[name=skill0]').textContent()).includes('文档摘要'), 'general skill visible');
  await page.getByRole('button', { name: '＋ 添加步骤', exact: true }).click();
  await page.locator('[name=skill1]').selectOption('文档摘要');
  await page.locator('[name=model1]').selectOption('演示模型 B');
  await page.locator('[name=confirm1]').selectOption('人工确认');
  await page.locator('[name=binding1][value="step:0"]').check();
  await page.locator('.compact-step').nth(1).locator('summary').click();
  await page.locator('[name=output1]').fill('整理为事实、判断、待确认三部分。');
  await page.screenshot({ path: '/tmp/workflow-editor-demo.png', fullPage: true });
  await page.getByRole('button', { name: '检查并保存', exact: true }).click();
  check(await page.evaluate(() => workflowStatus('评审与摘要') === '待启用' && !publishedFlows().includes('评审与摘要')), 'save defaults awaiting enable');
  check(await page.evaluate(() => flowInfo['评审与摘要'].bindings[1].includes('task') && flowInfo['评审与摘要'].bindings[1].includes('step:0')), 'previous result adds input without exclusion');
  check(await page.evaluate(() => flowInfo['评审与摘要'].settings[1].model === '演示模型 B' && flowInfo['评审与摘要'].settings[1].confirm === '人工确认' && !!flowInfo['评审与摘要'].settings[1].output && !!flowInfo['评审与摘要'].inputRequirements), 'settings saved');
  const card = page.locator('.compact-flow-card').filter({ has: page.getByRole('heading', { name: '评审与摘要', exact: true }) });
  await card.getByRole('button', { name: '启用', exact: true }).click();
  check(await page.evaluate(() => publishedFlows().includes('评审与摘要')), 'enabled workflow selectable');
  check(await card.getByRole('button', { name: '编辑', exact: true }).isDisabled(), 'enabled read only');
  await card.getByRole('button', { name: '查看', exact: true }).click();
  await page.getByRole('button', { name: '用于新任务', exact: true }).click();
  check(await page.locator('[name=target]').inputValue() === '评审与摘要', 'workflow handed to task');
  await page.getByRole('button', { name: '关闭弹窗', exact: true }).click();
  await page.evaluate(() => showFlows());
  await card.getByRole('button', { name: '停用', exact: true }).click();
  await page.getByRole('button', { name: '确认停用', exact: true }).click();
  check(await page.evaluate(() => workflowStatus('评审与摘要') === '已停用'), 'disabled state distinguishes never enabled');
  await card.getByRole('button', { name: '删除', exact: true }).click();
  await page.getByRole('button', { name: '确认删除', exact: true }).click();
  check(await page.evaluate(() => !Object.hasOwn(flows, '评审与摘要')), 'delete unused disabled workflow');
  await page.getByText('演示切换角色', { exact: true }).click();
  await page.getByLabel('演示角色').selectOption('运维工程师');
  check(await page.locator('.compact-flow-card').count() === 0, 'workflow role filtering');
  await page.getByRole('button', { name: '＋ 新建工作流', exact: true }).click();
  check(!(await page.locator('[name=skill0]').textContent()).includes('测试分析'), 'test skills hidden from operations');
  await page.locator('[name=flowName]').fill('巡检草稿');
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  check(await page.evaluate(() => workflowStatus('巡检草稿') === '草稿'), 'draft state');
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile list width');
  await page.getByRole('button', { name: '＋ 新建工作流', exact: true }).click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile editor width');
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>nav('workspace','HIS'));
  await page.locator('.composer textarea').fill('如何使用这个工作区？');
  await page.locator('.composer button').click();
  check(await page.getByText(/您可以让我整理工作思路/).count()>0,'general chat feedback');
  await page.locator('.composer textarea').fill('新建一个周期任务，每日17:00编写工作日报，并发邮件到madderli@新建一个周期任务');
  await page.locator('.composer button').click();
  check(await page.getByText('任务已整理 · 待确认',{exact:true}).count()>0,'inline task card');
  check(await page.locator('[name=email]').inputValue()==='','invalid email not accepted');
  check(await page.locator('[name=time]').inputValue()==='17:00','schedule extracted');
  check(await page.evaluate(()=>!modal.open&&S.page==='workspace'),'no creation page or modal');
  check(errors.length === 0, errors.join('\n'));
  console.log('PASS: compact list/editor, role filtering, additive input, model/confirmation/I-O settings, four states, enable gate, delete, responsive; no page errors.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
